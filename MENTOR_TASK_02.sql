--task 11
SELECT FIRST_NAME,
       SALARY,
       SALARY * 0.1 + SALARY * NVL(COMMISSION_PCT, 0) AS BONUS
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;

--task 12
SELECT FIRST_NAME,
       LAST_NAME,
       HIRE_DATE
FROM HR.EMPLOYEES
WHERE EXTRACT(YEAR FROM HIRE_DATE) > 2004
  AND EXTRACT(MONTH FROM HIRE_DATE) = 6;

--task 13
SELECT ROUND(AVG(SALARY)),MAX(SALARY),MIN(SALARY) FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID=50;

--task 14
SELECT SALARY * 12 AS ILLIK_BRUTO,
       ROUND(SALARY * 12 * 0.15, 2) AS ILLIK_VERGI,
       ROUND(SALARY * 12 * 0.85, 2) AS ILLIK_NET
FROM HR.EMPLOYEES;

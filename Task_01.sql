--TASK 1
SELECT FIRST_NAME,
       LAST_NAME,
       NVL(COMMISSION_PCT, 0) AS DUZELDILMIS_KOMISSIYA
FROM HR.EMPLOYEES;

--TASK 2
SELECT FIRST_NAME, LAST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE UPPER(LAST_NAME) = 'KING';

--TASK 3
SELECT FIRST_NAME,
       LAST_NAME,
       HIRE_DATE
FROM HR.EMPLOYEES
WHERE EXTRACT(YEAR FROM HIRE_DATE) >= 2006;


--TASK 4
SELECT FIRST_NAME,
       LAST_NAME,
       ROUND((DATE '2026-11-08' - HIRE_DATE) / 30) AS STAZ_AY
FROM HR.EMPLOYEES;

--TASK 5
SELECT FIRST_NAME,PHONE_NUMBER FROM HR.EMPLOYEES
WHERE PHONE_NUMBER LIKE '1.515%';

--TASK 6
SELECT JOB_TITLE,MIN_SALARY FROM HR.JOBS
WHERE MIN_SALARY<3000
ORDER BY MIN_SALARY DESC;

--TASK 7
SELECT CITY,STREET_ADDRESS FROM HR.LOCATIONS
WHERE POSTAL_CODE IS NULL;

--TASK 8
SELECT FIRST_NAME,LAST_NAME,
CONCAT(SALARY,'USD') AS SALARY
FROM HR.EMPLOYEES;

--TASK 9
SELECT COUNT(JOB_ID) FROM HR.JOBS
WHERE MAX_SALARY>20000;

--TASK 10
--HIRE_DATE=2005 OLANDA TARIXLE VERILEN REQEMI MUQAYISE EDE BILMIR VE XETA VERIR
SELECT FIRST_NAME, HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE BETWEEN DATE '2005-01-01' AND DATE '2005-12-31';

--TASK 11
SELECT FIRST_NAME,
       SALARY,
       ROUND(SALARY * 0.8, 2) AS NET_MAAS
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;

--TASK 12
SELECT FIRST_NAME,HIRE_DATE,JOB_ID FROM HR.EMPLOYEES
WHERE HIRE_DATE BETWEEN DATE '2003-01-01' AND DATE '2005-12-31' AND JOB_ID<>'IT_PROG' ;

--TASK 13
SELECT COUNT(*),
    ROUND(AVG(SALARY))
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NULL;    

--TASK 14
SELECT FIRST_NAME,SALARY FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL AND DEPARTMENT_ID IS NOT NULL 
ORDER BY SALARY DESC
FETCH FIRST 3 ROWS ONLY;

--TASK 15
SELECT FIRST_NAME,
LAST_NAME,
EXTRACT(DAY FROM HIRE_DATE)AS ISE_GIRME_GUNU
FROM HR.EMPLOYEES
WHERE SALARY BETWEEN 5000 AND 12000 AND EXTRACT(DAY FROM HIRE_DATE)>15;
